const races = new Set(read(new URL('races.json', DATA)).map((r) => r.id))
const counts = {}
for (const sp of species) {
  const raceId = REVIEW[sp.source]?.[sp.id]
  if (!raceId || sp.raceId !== 'mythicBeast') continue
  if (!races.has(raceId)) throw new Error(`Race không tồn tại "${raceId}" (${sp.id})`)
  sp.raceId = raceId
  counts[sp.source] = (counts[sp.source] ?? 0) + 1
}
